@app.post("/api/vital-signs", response_model=VitalSignsResponse, status_code=status.HTTP_201_CREATED)
async def record_vital_signs(
    vital_signs: VitalSignsInput,
    db: Session = Depends(get_db)
):
    """
    Record patient vital signs and detect anomalies
    
    This endpoint:
    1. Validates vital signs data
    2. Runs anomaly detection
    3. Stores data in database
    4. Generates alerts if anomalies detected
    5. Broadcasts real-time updates via WebSocket
    """
    try:
        # Run anomaly detection
        anomaly_score, is_anomaly = anomaly_detector.predict(vital_signs)
        
        # Create database record
        db_vital_signs = VitalSigns(
            patient_id=vital_signs.patient_id,
            heart_rate=vital_signs.heart_rate,
            blood_pressure_systolic=vital_signs.blood_pressure_systolic,
            blood_pressure_diastolic=vital_signs.blood_pressure_diastolic,
            oxygen_saturation=vital_signs.oxygen_saturation,
            temperature=vital_signs.temperature,
            respiratory_rate=vital_signs.respiratory_rate,
            anomaly_score=anomaly_score,
            is_anomaly=is_anomaly
        )
        
        db.add(db_vital_signs)
        db.commit()
        db.refresh(db_vital_signs)
        
        # Cache latest vital signs in Redis
        redis_key = f"patient:{vital_signs.patient_id}:latest"
        redis_client.setex(
            redis_key,
            300,  # 5 minutes TTL
            json.dumps({
                "heart_rate": vital_signs.heart_rate,
                "blood_pressure": f"{vital_signs.blood_pressure_systolic}/{vital_signs.blood_pressure_diastolic}",
                "oxygen_saturation": vital_signs.oxygen_saturation,
                "temperature": vital_signs.temperature,
                "respiratory_rate": vital_signs.respiratory_rate,
                "anomaly_score": anomaly_score,
                "is_anomaly": is_anomaly,
                "timestamp": datetime.utcnow().isoformat()
            })
        )
        
        # Generate alert if anomaly detected
        if is_anomaly:
            alert_type = "critical" if anomaly_score > 0.7 else "warning"
            alert_message = f"Anomaly detected in vital signs (score: {anomaly_score:.2f})"
            
            alert = Alert(
                patient_id=vital_signs.patient_id,
                alert_type=alert_type,
                message=alert_message,
                vital_signs_id=db_vital_signs.id
            )
            db.add(alert)
            db.commit()
            
            # Broadcast alert via WebSocket
            await manager.broadcast_alert(alert)
            
            logger.warning(f"Anomaly detected for patient {vital_signs.patient_id}: {alert_message}")
        
        # Broadcast vital signs update
        await manager.broadcast_to_patient(
            vital_signs.patient_id,
            {
                "type": "vital_signs",
                "data": {
                    "heart_rate": vital_signs.heart_rate,
                    "blood_pressure": f"{vital_signs.blood_pressure_systolic}/{vital_signs.blood_pressure_diastolic}",
                    "oxygen_saturation": vital_signs.oxygen_saturation,
                    "temperature": vital_signs.temperature,
                    "respiratory_rate": vital_signs.respiratory_rate,
                    "anomaly_score": anomaly_score,
                    "is_anomaly": is_anomaly,
                    "timestamp": db_vital_signs.timestamp.isoformat()
                }
            }
        )
        
        logger.info(f"Recorded vital signs for patient {vital_signs.patient_id}")
        return db_vital_signs
        
    except Exception as e:
        logger.error(f"Error recording vital signs: {e}")
        db.rollback()
        raise HTTPException(status_code=500, detail=f"Failed to record vital signs: {str(e)}")


@app.get("/api/patients/{patient_id}/vital-signs", response_model=List[VitalSignsResponse])
async def get_patient_vital_signs(
    patient_id: str,
    limit: int = 100,
    db: Session = Depends(get_db)
):
    """Get vital signs history for a patient"""
    vital_signs = db.query(VitalSigns).filter(
        VitalSigns.patient_id == patient_id
    ).order_by(VitalSigns.timestamp.desc()).limit(limit).all()
    
    return vital_signs


@app.get("/api/patients/{patient_id}/alerts", response_model=List[AlertResponse])
async def get_patient_alerts(
    patient_id: str,
    acknowledged: Optional[bool] = None,
    db: Session = Depends(get_db)
):
    """Get alerts for a patient"""
    query = db.query(Alert).filter(Alert.patient_id == patient_id)
    
    if acknowledged is not None:
        query = query.filter(Alert.acknowledged == acknowledged)
    
    alerts = query.order_by(Alert.timestamp.desc()).all()
    return alerts


@app.post("/api/alerts/{alert_id}/acknowledge")
async def acknowledge_alert(
    alert_id: int,
    acknowledged_by: str,
    db: Session = Depends(get_db)
):
    """Acknowledge an alert"""
    alert = db.query(Alert).filter(Alert.id == alert_id).first()
    
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")
    
    alert.acknowledged = True
    alert.acknowledged_by = acknowledged_by
    alert.acknowledged_at = datetime.utcnow()
    
    db.commit()
    
    logger.info(f"Alert {alert_id} acknowledged by {acknowledged_by}")
    return {"message": "Alert acknowledged successfully"}


