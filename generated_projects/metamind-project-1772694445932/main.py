class AnomalyDetector:
    """Isolation Forest based anomaly detector for vital signs"""
    
    def __init__(self):
        self.model = IsolationForest(
            contamination=0.1,
            random_state=42,
            n_estimators=100
        )
        self.is_trained = False
        self.feature_names = [
            'heart_rate', 'blood_pressure_systolic', 'blood_pressure_diastolic',
            'oxygen_saturation', 'temperature', 'respiratory_rate'
        ]
        logger.info("Anomaly detector initialized")
    
    def extract_features(self, vital_signs: VitalSignsInput) -> np.ndarray:
        """Extract features from vital signs"""
        return np.array([[
            vital_signs.heart_rate,
            vital_signs.blood_pressure_systolic,
            vital_signs.blood_pressure_diastolic,
            vital_signs.oxygen_saturation,
            vital_signs.temperature,
            vital_signs.respiratory_rate
        ]])
    
    def train(self, historical_data: List[VitalSignsInput]):
        """Train the model on historical data"""
        if len(historical_data) < 100:
            logger.warning(f"Insufficient training data: {len(historical_data)} samples")
            return
        
        features = np.vstack([self.extract_features(vs) for vs in historical_data])
        self.model.fit(features)
        self.is_trained = True
        logger.info(f"Model trained on {len(historical_data)} samples")
    
    def predict(self, vital_signs: VitalSignsInput) -> tuple[float, bool]:
        """
        Predict anomaly score and classification
        Returns: (anomaly_score, is_anomaly)
        """
        features = self.extract_features(vital_signs)
        
        if not self.is_trained:
            # Use rule-based detection if model not trained
            return self._rule_based_detection(vital_signs)
        
        # Get anomaly score (-1 for anomaly, 1 for normal)
        prediction = self.model.predict(features)[0]
        score = self.model.score_samples(features)[0]
        
        # Convert to 0-1 scale (higher = more anomalous)
        anomaly_score = float(1 / (1 + np.exp(score)))
        is_anomaly = prediction == -1
        
        return anomaly_score, is_anomaly
    
    def _rule_based_detection(self, vital_signs: VitalSignsInput) -> tuple[float, bool]:
        """Rule-based anomaly detection as fallback"""
        anomalies = 0
        total_checks = 6
        
        # Check each vital sign against normal ranges
        if not (60 <= vital_signs.heart_rate <= 100):
            anomalies += 1
        if not (90 <= vital_signs.blood_pressure_systolic <= 140):
            anomalies += 1
        if not (60 <= vital_signs.blood_pressure_diastolic <= 90):
            anomalies += 1
        if not (95 <= vital_signs.oxygen_saturation <= 100):
            anomalies += 1
        if not (97 <= vital_signs.temperature <= 99):
            anomalies += 1
        if not (12 <= vital_signs.respiratory_rate <= 20):
            anomalies += 1
        
        anomaly_score = anomalies / total_checks
        is_anomaly = anomaly_score > 0.3
        
        return anomaly_score, is_anomaly


